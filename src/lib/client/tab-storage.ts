import { STORAGE_KEY } from "./session";

type StoragePort = Pick<Storage, "getItem" | "setItem">;
type StorageEnvironment = {
  localStorage: StoragePort;
  sessionStorage: StoragePort;
  createId?: () => string;
};

export const TAB_POINTER_KEY = "incidentlab.tab.snapshot.v1";
const SNAPSHOT_PREFIX = `${STORAGE_KEY}.tab.`;
const STORAGE_WARNING = "Practice can continue in this tab, but this browser could not enable saving across reloads.";

/**
 * Call once after hydration. Every mount rotates the key, including duplicated tabs
 * that inherited sessionStorage. No tab writes another tab's snapshot or pointer.
 * Optional environment injection keeps the isolation behavior testable without a DOM.
 */
export function openTabStorage(environment?: StorageEnvironment): {
  storage: StoragePort;
  warning: string | null;
} {
  let memory: string | null = null;
  let local: StoragePort | null = null;
  let snapshotKey: string | null = null;
  let warning: string | null = null;
  try {
    const browser = environment ?? {
      localStorage: window.localStorage,
      sessionStorage: window.sessionStorage,
      createId: () => window.crypto.randomUUID(),
    };
    const previousKey = browser.sessionStorage.getItem(TAB_POINTER_KEY);
    // Only read keys generated by this adapter, never an arbitrary stored path.
    if (previousKey?.startsWith(SNAPSHOT_PREFIX)) {
      memory = browser.localStorage.getItem(previousKey);
    }
    const id = (browser.createId ?? (() => globalThis.crypto.randomUUID()))();
    if (!/^[a-zA-Z0-9_-]{1,100}$/.test(id)) throw new Error("Invalid snapshot ID");
    const nextKey = `${SNAPSHOT_PREFIX}${id}`;
    if (nextKey === previousKey) throw new Error("Snapshot ID must rotate");
    if (browser.localStorage.getItem(nextKey) !== null) throw new Error("Snapshot ID is already in use");
    // Confirm localStorage works before publishing the sessionStorage pointer.
    browser.localStorage.setItem(nextKey, memory ?? "");
    browser.sessionStorage.setItem(TAB_POINTER_KEY, nextKey);
    local = browser.localStorage;
    snapshotKey = nextKey;
  } catch {
    warning = STORAGE_WARNING;
  }

  const storage: StoragePort = {
    getItem: () => memory || null,
    setItem: (_key, value) => {
      // Preserve the active run even when quota/access changes during practice.
      memory = value;
      if (!local || !snapshotKey) throw new Error(STORAGE_WARNING);
      try {
        local.setItem(snapshotKey, value);
      } catch {
        local = null;
        throw new Error(STORAGE_WARNING);
      }
    },
  };
  return { storage, warning };
}
